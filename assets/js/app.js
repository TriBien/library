  /* ---------------- done / unread ---------------- */

  function isDone(id) {
    return Object.prototype.hasOwnProperty.call(state.done, id);
  }

  function setDone(book, done) {
    if (done) {
      state.done[book.id] = { finishedAt: Date.now() };
      delete state.removed[book.id]; // finished again, forget the tombstone
      toast('Added to Reading History');
    } else {
      delete state.done[book.id];
      state.removed[book.id] = Date.now(); // so the union cannot resurrect it
      toast('Moved back to Library');
    }
    touch();
    renderBadge();
  }

  function doneBooks() {
    return books
      .filter(function (book) {
        return isDone(book.id);
      })
      .sort(function (a, b) {
        return state.done[b.id].finishedAt - state.done[a.id].finishedAt;
      });
  }

  function unreadBooks() {
    return books.filter(function (book) {
      return !isDone(book.id);
    });
  }

  function findBook(id) {
    for (var i = 0; i < books.length; i++) {
      if (books[i].id === id) return books[i];
    }
    return null;
  }

  function renderBadge() {
    var count = Object.keys(state.done).length;
    els.badge.hidden = count === 0;
    els.badge.textContent = count > 99 ? '99+' : String(count);
  }

  /* ---------------- markdown ---------------- */

  var contentCache = {};

  function fetchMarkdown(book) {
    if (contentCache[book.id]) return Promise.resolve(contentCache[book.id]);
    var url = versioned(book.file, buildId || 'dev');
    return fetch(url, { cache: 'no-store' })
      .then(function (res) {
        if (!res.ok) throw new Error('HTTP ' + res.status);
        return res.text();
      })
      .then(function (text) {
        contentCache[book.id] = text;
        return text;
      });
  }

