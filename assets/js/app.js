  /* ---------------- library / history screens ---------------- */

  var collection = { refresh: function () {} };

  function renderCollection(kind) {
    var isHistory = kind === 'history';
    var query = '';
    var all = isHistory ? doneBooks() : unreadBooks();

    setScreens(
      isHistory ? 'Reading History' : 'Library',
      all.length
        ? all.length + (all.length === 1 ? ' book' : ' books') +
          (isHistory ? ' finished' : ' left to read')
        : ''
    );

    els.main.innerHTML = '';

    var toolbar = el('div', 'toolbar');
    var box = el('div', 'search');
    box.innerHTML = svg(ICONS.search, 'search__icon');

    var input = document.createElement('input');
    input.type = 'search';
    input.placeholder = isHistory ? 'Search finished books' : 'Search books or authors';
    input.setAttribute('aria-label', input.placeholder);

    var clear = iconButton(svg(ICONS.close), 'Clear search', {
      className: 'search__clear',
      handler: function () {
        input.value = '';
        query = '';
        clear.hidden = true;
        refresh();
        input.focus();
      }
    });
    clear.hidden = true;

    var count = el('p', 'count');

    var holder = el('div', 'holder');
    var listWrap = el('ul', 'list');

    function refresh() {
      all = isHistory ? doneBooks() : unreadBooks();
      var needle = query.toLowerCase();
      var visible = needle
        ? all.filter(function (book) {
            return (
              book.title.toLowerCase().indexOf(needle) !== -1 ||
              book.author.toLowerCase().indexOf(needle) !== -1
            );
          })
        : all;

      count.textContent = needle ? visible.length + ' of ' + all.length + ' shown' : '';
      listWrap.innerHTML = '';

      if (visible.length) {
        visible.forEach(function (book) {
          listWrap.appendChild(bookRow(book, isHistory));
        });
        holder.innerHTML = '';
        holder.appendChild(listWrap);
        return;
      }

      holder.innerHTML = '';
      if (needle) {
        holder.appendChild(
          emptyState('🔍', 'No matches', 'Try another title or author.')
        );
      } else if (all.length) {
        holder.appendChild(listWrap); // empty but non-empty list -> nothing to say
      } else if (isHistory) {
        holder.appendChild(
          emptyState(
            '📚',
            'Nothing finished yet',
            'Books you mark as Done land here, ready to re-read.'
          )
        );
      } else if (books.length) {
        holder.appendChild(
          emptyState(
            '🎉',
            'All caught up',
            'Every book is marked as Done. Re-read them in History.'
          )
        );
      } else {
        holder.appendChild(
          emptyState('📭', 'No books yet', 'Run python3 tools/build.py to load output/*.md.')
        );
      }
    }

    input.addEventListener('input', function () {
      query = input.value.trim();
      clear.hidden = !input.value;
      refresh();
    });

    box.appendChild(input);
    box.appendChild(clear);
    toolbar.appendChild(box);
    els.main.appendChild(toolbar);
    els.main.appendChild(count);
    els.main.appendChild(holder);

    collection.refresh = refresh;
    refresh();
    markActiveTab(isHistory ? 'history' : 'library');
  }

  /* ---------------- google drive sync ----------------
     One hidden document in the reader's own appDataFolder holds the whole
     library state. Merging is by timestamp, so two devices can both write
     without stepping on each other: per book the newer entry wins, and the
     single settings (theme, text size) follow whichever side wrote last. */

  function parseDoc(text) {
    var data;
    try {
      data = JSON.parse(text);
    } catch (err) {
      return null; // unreadable file, keep what is in memory
    }
    return cleanDoc(data);
  }

  /* takes anything shaped like a document and hands back only what is safe */
  function cleanDoc(data) {
    if (!data || typeof data !== 'object') return null;

    var doc = { version: DOC_VERSION, updatedAt: 0, theme: null, fontScale: 1, done: {}, lastRead: {}, removed: {} };
    if (typeof data.updatedAt === 'number') doc.updatedAt = data.updatedAt;
    if (data.theme === 'light' || data.theme === 'dark') doc.theme = data.theme;
    if (typeof data.fontScale === 'number') doc.fontScale = clamp(data.fontScale, FONT_MIN, FONT_MAX);
    if (data.done && typeof data.done === 'object') {
      Object.keys(data.done).forEach(function (id) {
        var entry = data.done[id];
        if (!entry || typeof entry.finishedAt !== 'number' || entry.finishedAt <= 0) return;
        doc.done[id] = { finishedAt: entry.finishedAt };
      });
    }
    if (data.lastRead && typeof data.lastRead === 'object') {
      Object.keys(data.lastRead).forEach(function (id) {
        var entry = data.lastRead[id];
        if (!entry || typeof entry.percent !== 'number' || !entry.updatedAt) return;
        doc.lastRead[id] = {
          percent: clamp(entry.percent, 0, 100),
          updatedAt: entry.updatedAt
        };
      });
    }
    if (data.removed && typeof data.removed === 'object') {
      Object.keys(data.removed).forEach(function (id) {
        var at = data.removed[id];
        if (typeof at === 'number' && at > 0) doc.removed[id] = at;
      });
    }
    return doc;
  }

  function unionKeys(a, b) {
    var keys = {};
    var id;
    for (id in a) if (Object.prototype.hasOwnProperty.call(a, id)) keys[id] = true;
    for (id in b) if (Object.prototype.hasOwnProperty.call(b, id)) keys[id] = true;
    return Object.keys(keys);
  }

  function mergeDocs(local, remote) {
    if (!remote) return local;

    var merged = {
      version: DOC_VERSION,
      updatedAt: Math.max(local.updatedAt || 0, remote.updatedAt || 0),
      theme: local.theme,
      fontScale: local.fontScale,
      done: {},
      lastRead: {},
      removed: {}
    };

    // theme and text size live in one place, so the newer document decides
    var newer = (remote.updatedAt || 0) > (local.updatedAt || 0) ? remote : local;
    merged.theme = newer.theme;
    merged.fontScale = newer.fontScale;

    // moving a book back to the Library is remembered, so a plain union of
    // the finished books cannot bring it back from the other device
    unionKeys(local.removed, remote.removed).forEach(function (id) {
      merged.removed[id] = Math.max(local.removed[id] || 0, remote.removed[id] || 0);
    });

    // a book counts as finished when the newest finishing date says so,
    // unless it was un-finished after that
    unionKeys(local.done, remote.done).forEach(function (id) {
      var winner = local.done[id];
      var theirs = remote.done[id];
      if (theirs && (!winner || (theirs.finishedAt || 0) > (winner.finishedAt || 0))) {
        winner = theirs;
      }
      if (!winner) return;
      var finishedAt = winner.finishedAt || 0;
      if ((merged.removed[id] || 0) >= finishedAt) return;
      merged.done[id] = { finishedAt: finishedAt };
      delete merged.removed[id]; // finished again after the removal, forget it
    });

    // reading positions: the newer resume point wins
    unionKeys(local.lastRead, remote.lastRead).forEach(function (id) {
      var winner = local.lastRead[id];
      var theirs = remote.lastRead[id];
      if (theirs && (!winner || (theirs.updatedAt || 0) > (winner.updatedAt || 0))) {
        winner = theirs;
      }
      if (winner) {
        merged.lastRead[id] = {
          percent: clamp(winner.percent || 0, 0, 100),
          updatedAt: winner.updatedAt || 0
        };
      }
    });

    return merged;
  }

  /* order-independent fingerprints, so a re-ordered document is not a change */
  function contentKey(doc) {
    function stamp(map) {
      return Object.keys(map || {})
        .sort()
        .map(function (id) {
          return id + ':' + (map[id] || 0);
        })
        .join(',');
    }
    function map(map) {
      return Object.keys(map || {})
        .sort()
        .map(function (id) {
          var entry = map[id] || {};
          return id + ':' + (entry.percent || 0) + ':' + (entry.finishedAt || entry.updatedAt || 0);
        })
        .join(',');
    }
    return map(doc.done) + '|' + map(doc.lastRead) + '|' + stamp(doc.removed);
  }

  function docKey(doc) {
    return [doc.theme, doc.fontScale, contentKey(doc)].join('|');
  }

  function applyDoc(doc) {
    var changed = false;

    if (doc.theme !== state.theme) {
      state.theme = doc.theme;
      applyTheme();
      changed = true;
    }
    if (doc.fontScale !== state.fontScale) {
      state.fontScale = doc.fontScale;
      applyFontScale();
      changed = true;
    }
    if (contentKey(state) !== contentKey(doc)) {
      state.done = doc.done;
      state.lastRead = doc.lastRead;
      state.removed = doc.removed || {};
      changed = true;
    }
    state.updatedAt = doc.updatedAt || 0;

    if (changed) {
      renderBadge();
      if (route.name === 'library' || route.name === 'history') collection.refresh();
    }
    return changed;
  }

  function scheduleSync() {
    if (!signedIn()) return;
    clearTimeout(syncTimer);
    syncTimer = setTimeout(function () {
      syncNow({ interactive: false });
    }, SYNC_DELAY);
  }

  /* Pull, merge, push back only when the merge says something new happened. */
  function syncNow(options) {
    var opts = options || {};
    if (!signedIn()) return Promise.resolve('signed-out');
    if (syncRunning) return Promise.resolve('busy');

    syncRunning = true;
    setStatus('Syncing with Drive…');

    var token = auth.accessToken;
    var name = config.driveFileName;

    return GDrive.findFile(token, name)
      .then(function (file) {
        if (!file) return { file: null, remote: null };
        return GDrive.readFile(token, file.id).then(function (text) {
          return { file: file, remote: parseDoc(text) };
        });
      })
      .then(function (found) {
        var doc = mergeDocs(toDoc(state), found.remote);
        applyDoc(doc);

        if (found.remote && docKey(found.remote) === docKey(doc)) return null;

        doc.updatedAt = Date.now();
        var body = JSON.stringify(doc, null, 2);
        var saving = found.file
          ? GDrive.updateFile(token, found.file.id, body)
          : GDrive.createFile(token, name, body);

        return saving.catch(function (err) {
          // deleted from another tab, or the id went stale: write a new one
          if (err.status !== 404) throw err;
          return GDrive.createFile(token, name, body);
        }).then(function (saved) {
          if (saved && saved.id) patchAuth({ fileId: saved.id });
          state.updatedAt = doc.updatedAt; // memory and Drive now agree on "newest"
        });
      })
      .then(
        function () {
          syncRunning = false;
          syncedOnce = true;
          // Drive has the state now, so the pre-sign-in copy has done its job
          clearTemp();
          patchAuth({ lastSyncedAt: Date.now() });
          setStatus('Synced ' + timeAgo(Date.now()));
          renderOnce();
          if (route.name === 'account') renderAccount();
          renderAppbarActions();
          return true;
        },
        function (err) {
          var first = !syncedOnce; // the pull that fills the screen on arrival
          syncRunning = false;
          syncedOnce = true;
          if (err && err.code === 'expired') {
            saveAuth(null);
            saveTemp(); // keep what we have until the next sign-in
          }
          setStatus(err && err.message ? err.message : 'Sync failed.', true);
          renderOnce();
          if (route.name === 'account') renderAccount();
          renderAppbarActions();
          if (first) toast('Could not reach Drive — your library loads once it answers');
          if (opts.interactive) throw err;
          return false;
        }
      );
  }

  function signIn() {
    if (!config.googleClientId) {
      setStatus('Google sign-in is not configured yet.', true);
      renderAccount();
      return;
    }

    setStatus('Waiting for Google…');
    renderAccount();

    GDrive.signIn({ clientId: config.googleClientId, quiet: !!auth })
      .then(function (session) {
        setStatus('Reading your account…');
        return GDrive.profile(session.accessToken).then(
          function (who) {
            return who;
          },
          function () {
            return null; // the name is decoration, the token is what matters
          }
        ).then(function (who) {
          saveAuth({
            clientId: config.googleClientId,
            accessToken: session.accessToken,
            expiresAt: session.expiresAt,
            name: who ? who.name : '',
            email: who ? who.email : '',
            picture: who ? who.picture : '',
            signedInAt: Date.now(),
            lastSyncedAt: 0,
            fileId: (auth && auth.fileId) || ''
          });
          renderAppbarActions();
          return syncNow({ interactive: true });
        });
      })
      .then(function (result) {
        if (result === true) toast('Signed in — your library is in sync');
        renderAccount();
      })
      .catch(function (err) {
        setStatus(err && err.message ? err.message : 'Sign-in failed.', true);
        renderAccount();
      });
  }

  function signOut() {
    var token = auth && auth.accessToken;
    saveAuth(null);
    accountStatus = null;
    saveTemp(); // Drive still has everything; this copy only covers being offline
    renderAppbarActions();
    renderAccount();
    toast('Signed out — nothing was deleted');
    if (token) GDrive.revoke(token);
  }

  function setStatus(text, isError) {
    accountStatus = { text: text, error: !!isError };
  }

