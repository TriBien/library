  /* ---------------- book card ---------------- */

  function bookRow(book, showDate) {
    var done = isDone(book.id);
    var resume = state.lastRead[book.id];

    var meta = [];
    if (showDate) meta.push('Finished ' + formatDate(state.done[book.id].finishedAt));
    meta.push(book.minutes + ' min read');
    if (book.words) meta.push(book.words.toLocaleString() + ' words');
    if (resume && !showDate && resume.percent > 2 && resume.percent < 97) {
      meta.push(Math.round(resume.percent) + '% read');
    }

    var row = el('li', 'row');
    var link = el('a', 'card');
    link.href = '#/book/' + encodeURIComponent(book.id);
    link.innerHTML =
      '<span class="card__cover" aria-hidden="true">' +
      escapeHtml(initials(book.title)) +
      '</span>' +
      '<span class="card__body">' +
      '<span class="card__title">' +
      escapeHtml(book.title) +
      '</span>' +
      '<span class="card__author">' +
      escapeHtml(book.author) +
      '</span>' +
      (book.excerpt ? '<span class="card__excerpt">' + escapeHtml(book.excerpt) + '</span>' : '') +
      '<span class="card__meta">' +
      meta.map(escapeHtml).join('<span class="dot">·</span>') +
      '</span>' +
      '</span>';

    var action = el(
      'button',
      'card__action' + (done ? ' is-done' : ''),
      done ? svg(ICONS.undo) : svg(ICONS.checkCircle)
    );
    action.type = 'button';
    action.title = done ? 'Move back to Library' : 'Mark as Done';
    action.setAttribute('aria-label', action.title);
    action.addEventListener('click', function () {
      setDone(book, !done);
      collection.refresh();
    });

    row.appendChild(link);
    row.appendChild(action);
    return row;
  }

